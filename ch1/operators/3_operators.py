# ARITHMETIC OPERATORS
# + is the addition operator
a = 5
b = 6
c = a + b
print(c)
# Output: 11


# ASSIGNMENT OPERATORS
# = is the assignment operator
# It assigns the result of 10 - 4 to variable 'a'
a = 10 - 4
print(a)
# Output: 6

# += OPERATOR
# += is the addition assignment operator
# b = b + 3
b = 5
b += 3 # It increases the value of b by 3
print(b)
# Output: 8


# -= OPERATOR
# -= is the subtraction assignment operator
b -= 2 # It decreases the value of b by 2
print(b)
# Output: 6



#  COMPARISON OPERATORS
# < means "less than"
# Check whether 10 is less than 2
c = 10 < 2
print(c)
# Output: False     ------- alway come boolean value True or False

# <= means "less than or equal to"
# Check whether 33 is less than or equal to 2
f = 33 <= 2
print(f)
# Output: False


# LOGICAL OPERATORS
# TRUTH TABLE OF OR
l = True or False
print(l)
# Output: True
print("True or False is", True or False)
# Output: True or False is True
print("True or True is", True or True)
# Output: True or True is True
print("False or True is", False or True)
# Output: False or True is True
print("False or False is", False or False)
# Output: False or False is False

# TRUTH TABLE OF AND
print("True and False is", True and False)
# Output: True and False is False
print("True and True is", True and True)
# Output: True and True is True
print("False and True is", False and True)
# Output: False and True is False
print("False and False is", False and False)
# Output: False and False is False