# INPUT FUNCTION
# By default input() returns a string.
a = input("Enter a number 1 : ")
b = input("Enter a number 2 : ")
print("Number 1 is : " + a)
print("Number 2 is : " + b)
# joins (concatenates) the two strings
# It does NOT perform mathematical addition
print("The sum is :", a + b)

